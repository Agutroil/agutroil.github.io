#!/usr/bin/env python3
"""Build static Codex pages, the runtime catalogue and sitemap from public JSON only."""
from __future__ import annotations

import argparse
from copy import deepcopy
from datetime import datetime
from html import escape
from hashlib import sha256
import json
from pathlib import Path
import re
from string import Template
import unicodedata
from urllib.parse import urljoin
import xml.etree.ElementTree as ET

from site_assets import ROOT, image_size

BASE = 'https://agutroil.github.io'
DATABASE = ROOT / 'Nythara/database'
DATA = DATABASE / 'data'
PREFIX = '/Nythara/database/'
TYPES = {'item': 'Item', 'equipment': 'Equipment', 'monster': 'Monster', 'boss': 'Boss', 'dungeon': 'Dungeon', 'region': 'Region', 'city': 'City', 'npc': 'NPC', 'quest': 'Quest', 'skill': 'Skill', 'resource': 'Resource', 'loot': 'Loot table'}
HIDDEN_FACTS = {'Stable ID', 'World ID', 'Map ID', 'Appearance ID'}
MARKER = '<!-- Generated by tools/build_nythara_pages.py;'


def entity_key(kind: str, entry_id: str) -> str:
    return f"{ {'boss': 'monster', 'equipment': 'item'}.get(kind, kind)}/{entry_id}"


def slug(entry_id: str) -> str:
    value = re.sub(r'^(enemy|world|weapon|skill|npc|quest|item|loot|resource|armor|accessory)_', '', entry_id)
    return re.sub(r'[^a-z0-9]+', '-', unicodedata.normalize('NFKD', value).encode('ascii', 'ignore').decode().lower()).strip('-')


def outgoing(entry: dict) -> list[dict]:
    return [link for section in entry.get('sections', []) for link in section.get('links', [])]


def facts_markup(facts: list[dict]) -> str:
    rows = ''.join(f'<div><dt>{escape(str(f["label"]))}</dt><dd>{escape(str(f["value"]))}</dd></div>' for f in facts if f['label'] not in HIDDEN_FACTS)
    return f'<dl class="static-facts">{rows}</dl>' if rows else ''


def describe(entry: dict) -> str:
    if entry.get('description'):
        return entry['description']
    facts = [f'{f["label"]}: {f["value"]}' for f in entry.get('facts', []) if f['label'] not in HIDDEN_FACTS][:3]
    return f'{entry["name"]} — {TYPES[entry["type"]].lower()} in Nythara. ' + '. '.join(facts) + '.'


def image_markup(entry: dict) -> str:
    src = urljoin(PREFIX, entry['image'])
    alt = escape(entry.get('image_alt') or entry['name'])
    if crop := entry.get('image_crop'):
        x, y, width, height, source_width, source_height = crop
        picture = f'<svg viewBox="{x} {y} {width} {height}" role="img" aria-label="{alt}" preserveAspectRatio="xMidYMid slice"><image href="{escape(src)}" width="{source_width}" height="{source_height}"></image></svg>'
    else:
        width, height = image_size(DATABASE / entry['image'])
        picture = f'<img src="{escape(src)}" alt="{alt}" width="{width}" height="{height}" decoding="async">'
    note = f'<span class="preview-note">{escape(entry["image_note"])}</span>' if entry.get('image_note') else ''
    if entry['image_kind'] == 'capture':
        picture = f'<a class="full-capture" href="{escape(src)}" aria-label="View full image: {alt}">{picture}<span aria-hidden="true">View full image ↗</span></a>'
    return f'<div class="detail-media is-{escape(entry["image_kind"])}">{picture}{note}</div>'


def build_outputs() -> dict[Path, str]:
    metadata = json.loads((DATA / 'metadata.json').read_text())
    categories = {c['key']: json.loads((DATA / f'{c["key"]}.json').read_text()) for c in metadata['categories']}
    if metadata.get('warnings') or metadata.get('errors'):
        raise ValueError('Resolve database export diagnostics before publishing')
    for category in metadata['categories']:
        payload = categories[category['key']]
        if payload['count'] != len(payload['entries']) or category['count'] != payload['count']:
            raise ValueError(f'Inconsistent category count: {category["key"]}')
    all_entries = [e for payload in categories.values() for e in payload['entries']]
    # Equipment/items and bosses/monsters share a single canonical page per entity.
    unique = {}
    for entry in all_entries:
        unique[entity_key(entry['type'], entry['id'])] = entry
    if len(unique) != metadata['total_primary_entries']:
        raise ValueError('Inconsistent unique entity count')
    for entry in all_entries:
        for link in outgoing(entry):
            if entity_key(link['type'], link['id']) not in unique:
                raise ValueError(f'Unresolved relationship from {entry["id"]}: {link["id"]}')
    paths = {key: f'{PREFIX}{entry["type"]}/{slug(entry["id"])}/' for key, entry in unique.items()}
    if len(set(paths.values())) != len(paths):
        raise ValueError('Static permalink collision')
    aliases = {f'{e["type"]}/{e["id"]}': paths[entity_key(e['type'], e['id'])] for e in all_entries}
    template = Template((ROOT / 'tools/templates/codex.html').read_text())
    outputs = {}
    urls = ['/', '/Nythara/', PREFIX]

    def links_markup(entries: list[dict]) -> str:
        links = ''.join(f'<li><a href="{escape(paths[entity_key(e["type"], e["id"])])}"><strong>{escape(e["name"])}</strong><span>{escape(TYPES[e["type"]])}</span></a></li>' for e in entries)
        return f'<ul class="static-entry-list">{links}</ul>'

    def page(path: str, title: str, description: str, crumbs: list[tuple[str, str]], content: str, entity: dict | None = None) -> None:
        description = re.sub(r'\s+', ' ', description).strip()
        if len(description) > 160:
            description = description[:157].rsplit(' ', 1)[0] + '…'
        breadcrumb_items = [{'@type': 'ListItem', 'position': i + 1, 'name': name, 'item': BASE + href} for i, (name, href) in enumerate(crumbs)]
        structured = {'@context': 'https://schema.org', '@graph': [
            {'@type': 'WebPage' if entity else 'CollectionPage', 'name': title, 'url': BASE + path, 'description': description,
             'isPartOf': {'@type': 'WebSite', 'name': 'Nythara', 'url': BASE + '/Nythara/'},
             'about': {'@type': 'VideoGame', 'name': 'Nythara', 'url': BASE + '/Nythara/'}},
            {'@type': 'BreadcrumbList', 'itemListElement': breadcrumb_items},
        ]}
        visual_crumbs = ''.join(f'<li><a href="{escape(href)}">{escape(name)}</a></li>' if i < len(crumbs) - 1 else f'<li aria-current="page">{escape(name)}</li>' for i, (name, href) in enumerate(crumbs))
        html = template.substitute(title=escape(title), description=escape(description, quote=True), canonical=escape(BASE + path),
            structured_data=json.dumps(structured, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c'),
            breadcrumbs=f'<nav class="static-crumbs" aria-label="Breadcrumb"><ol>{visual_crumbs}</ol></nav>', content=content, revision=escape(metadata['source_short_commit']))
        outputs[ROOT / path.lstrip('/') / 'index.html'] = '\n'.join(line.rstrip() for line in html.splitlines()) + '\n'
        urls.append(path)

    index_path = PREFIX + 'entries/'
    category_links = ''.join(f'<li><a href="{PREFIX}{c["type"]}/"><strong>{escape(c["label"])}</strong><span>{c["count"]} entries</span></a></li>' for c in metadata['categories'])
    page(index_path, 'Browse the Codex · Nythara Database', 'Browse Nythara’s creatures, dungeons, equipment, regions, quests and skills. Every Codex entry is available on its own permanent page.',
         [('Nythara', '/Nythara/'), ('Database', PREFIX), ('Codex', index_path)],
         f'<header class="static-intro"><p class="eyebrow">The world Codex</p><h1>Follow the trail.</h1><p>Discover a creature, explore its home and find the gear for your next adventure.</p><a class="button" href="{PREFIX}">Search the Database →</a></header><ul class="static-entry-list">{category_links}</ul>')

    for category in metadata['categories']:
        path = PREFIX + category['type'] + '/'
        entries = sorted(categories[category['key']]['entries'], key=lambda e: e['name'])
        page(path, category['label'] + ' · Nythara Database', category['description'] + ' Explore the Nythara Codex.',
             [('Nythara', '/Nythara/'), ('Database', PREFIX), (category['label'], path)],
             f'<header class="static-intro"><p class="eyebrow">Nythara Codex</p><h1>{escape(category["label"])}</h1><p>{escape(category["description"])}</p><a class="button button--ghost" href="{PREFIX}#{category["key"]}">Search &amp; filter {escape(category["label"].lower())} →</a></header>{links_markup(entries)}')

    for key, entry in unique.items():
        path = paths[key]
        category = next(c for c in metadata['categories'] if c['type'] == entry['type'])
        related = {entity_key(l['type'], l['id']): unique[entity_key(l['type'], l['id'])] for l in outgoing(entry) if entity_key(l['type'], l['id']) in unique and entity_key(l['type'], l['id']) != key}
        for other_key, other in unique.items():
            if other_key != key and any(entity_key(l['type'], l['id']) == key for l in outgoing(other)):
                related[other_key] = other
        sections = ''
        for section in entry.get('sections', []):
            linked = [unique[entity_key(l['type'], l['id'])] for l in section.get('links', []) if entity_key(l['type'], l['id']) in unique]
            body = facts_markup(section.get('facts', [])) + (links_markup(linked) if linked else '')
            if body:
                sections += f'<section class="static-section"><h2>{escape(section["title"])}</h2>{body}</section>'
        related_html = f'<section class="static-section"><h2>Related Entries</h2>{links_markup(sorted(related.values(), key=lambda e:e["name"]))}</section>' if related else ''
        description = describe(entry)
        content = f'''<article class="detail-record" data-variant="{escape(entry['type'])}">
  <header class="detail-hero">
    {image_markup(entry)}
    <div class="detail-copy"><p class="eyebrow">{TYPES[entry['type']]} · Nythara Codex</p><h1>{escape(entry['name'])}</h1>
      <p class="detail-description">{escape(description)}</p>
      <a class="button" href="{PREFIX}#{entry['type']}/{escape(entry['id'])}">Open in the interactive Database →</a>
    </div>
  </header>
  <section class="static-section"><h2>At a glance</h2>{facts_markup(entry.get('facts', []))}</section>
  {sections}{related_html}
</article>'''
        page(path, f'{entry["name"]} · {TYPES[entry["type"]]} · Nythara Database', description,
             [('Nythara', '/Nythara/'), ('Database', PREFIX), (category['label'], PREFIX + entry['type'] + '/'), (entry['name'], path)], content, entry)

    # Generate the existing landing UI once, avoiding a second DOM build at startup.
    category_by_key = {c['key']: c for c in metadata['categories']}
    primary_keys = ['items', 'monsters', 'bosses', 'dungeons', 'regions', 'cities']
    secondary_keys = ['equipment', 'npcs', 'quests', 'skills', 'resources', 'loot']

    def home_card(category: dict, primary: bool) -> str:
        count = category['count']
        return f"""<a class="category-card{' category-card--primary' if primary else ''}" href="#{category['key']}">
  <span class="category-arrow" aria-hidden="true">↗</span>
  <span class="category-icon"><svg class="icon" aria-hidden="true"><use href="#i-{category['key']}"></use></svg></span>
  <span class="category-label">{escape(category['label'])}</span>
  <span class="category-count">{count} {'entry' if count == 1 else 'entries'}</span>
  <span class="category-desc">{escape(category['description'])}</span>
</a>"""
    overview = ''.join(f'<a href="#{key}"><strong>{category_by_key[key]["count"]}</strong><span>{escape("Regions" if key == "regions" else category_by_key[key]["label"])}</span></a>' for key in ['items', 'equipment', 'monsters', 'bosses', 'dungeons', 'regions'])
    home_content = Template((ROOT / 'tools/templates/database-home-content.html').read_text()).substitute(
        total=metadata['total_primary_entries'], overview=overview,
        primary='\n'.join(home_card(category_by_key[key], True) for key in primary_keys),
        secondary='\n'.join(home_card(category_by_key[key], False) for key in secondary_keys))
    updated = datetime.fromisoformat(metadata['generated_at'].replace('Z', '+00:00'))
    outputs[DATABASE / 'index.html'] = Template((ROOT / 'tools/templates/database-home.html').read_text()).substitute(
        home_content=home_content, primary_count=metadata['total_primary_entries'], revision=metadata['source_short_commit'],
        category_count=len(metadata['categories']), updated_date=f'{updated:%b} {updated.day}, {updated.year}')

    # One runtime request replaces the metadata + category request waterfall.
    runtime = deepcopy(categories)
    dimensions = {}
    for entry in all_entries:
        for visual in [entry, *entry.get('image_extras', [])]:
            dimensions[visual['image']] = image_size(DATABASE / visual['image'])
    payload = {'metadata': metadata, 'previewFallbacks': json.loads((DATA / 'preview-fallbacks.json').read_text()),
               'categories': runtime, 'permalinks': aliases, 'imageDimensions': dimensions}
    outputs[DATA / 'catalogue.json'] = json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + '\n'
    catalogue_revision = sha256(outputs[DATA / 'catalogue.json'].encode()).hexdigest()[:12]
    outputs[DATABASE / 'index.html'] = outputs[DATABASE / 'index.html'].replace('__CATALOGUE_REVISION__', catalogue_revision)
    outputs[DATA / 'permalinks.json'] = json.dumps(aliases, ensure_ascii=False, indent=2) + '\n'
    namespace = 'http://www.sitemaps.org/schemas/sitemap/0.9'
    ET.register_namespace('', namespace)
    sitemap = ET.Element(f'{{{namespace}}}urlset')
    for path in sorted(set(urls)):
        url = ET.SubElement(sitemap, f'{{{namespace}}}url')
        ET.SubElement(url, f'{{{namespace}}}loc').text = BASE + path
    ET.indent(sitemap, space='  ')
    outputs[ROOT / 'sitemap.xml'] = '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(sitemap, encoding='unicode') + '\n'
    outputs[DATA / 'static-pages.json'] = json.dumps(sorted(str(p.relative_to(ROOT)) for p in outputs if p.suffix == '.html'), indent=2) + '\n'
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated output differs; write nothing.')
    args = parser.parse_args()
    outputs = build_outputs()
    manifest = DATA / 'static-pages.json'
    previous = json.loads(manifest.read_text()) if manifest.is_file() else []
    previous_paths = [(ROOT / path).resolve() for path in previous]
    if any(not path.is_relative_to(DATABASE) or path.suffix != '.html' for path in previous_paths):
        raise ValueError('Generated-page manifest contains an invalid output path')
    stale = [path for path in previous_paths if path not in outputs]
    different = [str(p.relative_to(ROOT)) for p, content in outputs.items() if not p.is_file() or p.read_text() != content]
    if args.check:
        if different or stale:
            raise SystemExit('Regenerate static pages: ' + ', '.join(different + [str(p.relative_to(ROOT)) for p in stale]))
    else:
        for path in stale:
            if path.is_file() and MARKER in path.read_text():
                path.unlink()
        for path, content in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f'Generated Codex HTML: {sum(p.suffix == ".html" for p in outputs)} pages; public JSON only.')


if __name__ == '__main__':
    main()
